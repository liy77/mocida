#!/usr/bin/env python3
"""Generates mui-runtime/src/device_frame_catalog.rs from the device-frames-media
index (https://github.com/jonnyjackson26/device-frames-media).

Only measurements and paths are kept: the frame and mask PNGs themselves are
downloaded on demand by mui-runtime (device_frames.rs) into the user's cache.

    python3 gen_frame_catalog.py [index.json]

Without an argument the index is fetched from GitHub.
"""
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

INDEX_URL = ("https://raw.githubusercontent.com/jonnyjackson26/device-frames-media/"
             "main/device-frames-output/index.json")
URL_PREFIX = ("https://raw.githubusercontent.com/jonnyjackson26/device-frames-media/"
              "main/device-frames-output/")

# Screen width in points (dp on Android) of each model, held upright. The height
# follows the frame's screen aspect. Safe areas: (top, bottom) in points.
POINTS = {
    "apple-iphone": {
        "17-pro-max": 440, "17-pro": 402, "air": 420, "16-pro-max": 440, "16-pro": 402,
        "16-plus": 430, "16": 393, "15-pro-max": 430, "15": 393, "14-pro-max": 430,
        "13": 390, "13-mini": 375, "12-pro-max": 428, "11-pro-max": 414, "11-pro": 375,
        "11": 414, "xs": 375, "8-plus": 414, "8": 375, "6s": 375,
    },
    "apple-ipad": {
        "ipad-air-10-9-m1": 820, "ipad-air-11-m2-m3": 820, "ipad-air-13-m2-m3": 1024,
        "ipad-pro-11-a12x-to-m2": 834, "ipad-pro-11-m4-m5": 834,
        "ipad-pro-13-a12x-to-m2": 1024, "ipad-pro-13-m4-m5": 1032,
        "ipad-mini-8-3-a17-pro": 744,
    },
    "android-phone": {
        "pixel-8": 412, "pixel-8-pro": 448, "pixel-9-pro": 427, "pixel-9-pro-xl": 448,
        "samsung-galaxy-s21": 360,
    },
    "android-tablet": {"pixel-tablet": 1280, "samsung-galaxy-tab-s11-ultra": 1480},
}

ISLAND = {"14-pro-max", "15", "15-pro-max", "16", "16-plus", "16-pro", "16-pro-max",
          "17-pro", "17-pro-max", "air"}
HOME_BUTTON = {"8", "8-plus", "6s"}


def safe_area(category, model):
    if category == "apple-iphone":
        if model in HOME_BUTTON:
            return 20, 0
        if model in ISLAND:
            return (62 if model in {"16-pro", "16-pro-max", "17-pro", "17-pro-max"} else 59), 34
        return {"13": 47, "12-pro-max": 47, "13-mini": 50, "11": 48}.get(model, 44), 34
    if category == "apple-ipad":
        return 24, 20
    if category == "android-phone":
        return 40, 24
    return 24, 24


def name_of(category, model):
    parts = model.split("-")
    if category == "apple-iphone":
        words = " ".join(p.capitalize() if not p.isdigit() else p for p in parts)
        return f"iPhone {words}".replace("Xs", "XS").replace("Mini", "mini")
    if category == "apple-ipad":
        known = {
            "ipad-air-10-9-m1": "iPad Air 10.9 (M1)", "ipad-air-11-m2-m3": "iPad Air 11 (M2/M3)",
            "ipad-air-13-m2-m3": "iPad Air 13 (M2/M3)", "ipad-pro-11-a12x-to-m2": "iPad Pro 11 (A12X–M2)",
            "ipad-pro-11-m4-m5": "iPad Pro 11 (M4/M5)", "ipad-pro-13-a12x-to-m2": "iPad Pro 13 (A12X–M2)",
            "ipad-pro-13-m4-m5": "iPad Pro 13 (M4/M5)", "ipad-mini-8-3-a17-pro": "iPad mini 8.3 (A17 Pro)",
        }
        return known.get(model, model)
    known = {"pixel-8": "Pixel 8", "pixel-8-pro": "Pixel 8 Pro", "pixel-9-pro": "Pixel 9 Pro",
             "pixel-9-pro-xl": "Pixel 9 Pro XL", "samsung-galaxy-s21": "Galaxy S21",
             "pixel-tablet": "Pixel Tablet", "samsung-galaxy-tab-s11-ultra": "Galaxy Tab S11 Ultra"}
    return known.get(model, model)


def device_id(category, model):
    prefix = {"apple-iphone": "iphone-", "apple-ipad": "", "android-phone": "",
              "android-tablet": ""}[category]
    return (prefix + model).replace("samsung-", "")


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    if len(sys.argv) > 1:
        index = json.loads(Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(INDEX_URL) as r:
            index = json.loads(r.read())
    out = [
        "// @generated by mocida-rs/assets/devices/gen_frame_catalog.py — do not edit.",
        "// Measurements from https://github.com/jonnyjackson26/device-frames-media;",
        "// the frame / mask PNGs are downloaded on demand (see device_frames.rs).",
        "",
        "use crate::device_frames::{FrameDevice, Variant};",
        "",
        "pub const FRAME_DEVICES: &[FrameDevice] = &[",
    ]
    for category in ["apple-iphone", "android-phone", "apple-ipad", "android-tablet"]:
        for model, variants in index.get(category, {}).items():
            width_pts = POINTS.get(category, {}).get(model)
            if not width_pts:
                continue
            first = next(iter(variants.values()))
            sx, sy = first["screen"]["x"], first["screen"]["y"]
            sw, sh = first["screen"]["width"], first["screen"]["height"]
            fw, fh = first["frameSize"]["width"], first["frameSize"]["height"]
            # Points keep the frame's screen aspect (a landscape-native tablet
            # frame stays landscape).
            height_pts = round(sh * width_pts / sw)
            top, bottom = safe_area(category, model)
            vs = []
            for vkey, v in variants.items():
                rel = urllib.parse.unquote(v["frame"][len(URL_PREFIX):-len("/frame.png")])
                color_name = rel.rsplit("/", 1)[-1]
                vs.append(f"Variant {{ id: {rust_str(vkey)}, name: {rust_str(color_name)}, "
                          f"path: {rust_str(rel)}, color: {rust_str(v.get('hexColor', ''))} }}")
            os_name = "ios" if category.startswith("apple") else "android"
            kind = "tablet" if "tablet" in category or "ipad" in category else "phone"
            out.append("    FrameDevice {")
            out.append(f"        id: {rust_str(device_id(category, model))},")
            out.append(f"        name: {rust_str(name_of(category, model))},")
            out.append(f"        os: {rust_str(os_name)},")
            out.append(f"        kind: {rust_str(kind)},")
            out.append(f"        points: ({width_pts}, {height_pts}),")
            out.append(f"        safe: ({top}, {bottom}),")
            out.append(f"        screen: ({sx}, {sy}, {sw}, {sh}),")
            out.append(f"        frame: ({fw}, {fh}),")
            out.append("        variants: &[")
            for v in vs:
                out.append(f"            {v},")
            out.append("        ],")
            out.append("    },")
    out.append("];")
    dest = Path(__file__).resolve().parents[2] / "mui-runtime" / "src" / "device_frame_catalog.rs"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
